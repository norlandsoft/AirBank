export type I18nKey = keyof typeof zh
const dicts: Record<Locale, typeof zh> = { 'zh-CN': zh, 'en-US': en }

export function translate(locale: Locale, key: I18nKey, vars?: Record<string, string>): string {
  let text: string = dicts[locale][key] ?? dicts['zh-CN'][key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value)
  }
  return text
}